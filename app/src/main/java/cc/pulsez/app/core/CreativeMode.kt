package cc.pulsez.app.core

/**
 * 「创作模式」的内核文案。
 *
 * 背景：用户原设想是「检测到深度沉浸 → 请确认你在创作 + 确认不会伤害自己才继续」，
 * 为兼顾法律、安全与使用体验，采用以下边界：
 * 不做自动检测、不做任何"确认不伤害自己"、不阻断服务。最终方案是**用户主动开启**的
 * 创作模式（默认关），只在 ① 层追加一段「创作层」，边界不变。
 *
 * 本对象是纯 Kotlin、不碰 Android，方便单测逐字断言文案（`CreativeModeTest`）。
 */
object CreativeMode {

    /**
     * ① 层人设末尾追加的创作层文本（**逐字保留**）。
     *
     * 四条边界一个都不能少：
     * 1. 不美化伤害自己或别人（拟人化办法第 8 条：不得鼓励/美化/暗示自残自杀）；
     * 2. 不写露骨性内容（生成式 AI 办法第 4 条、生态治理规定第 7 条）；
     * 3. 不诱导用户分不清故事与现实（AI 标识义务，deepfake/沉浸式拟真场景须显著标识）；
     * 4. 被问"是不是真人"时仍要诚实——该底线已统一收口在 `PromptAssembler.buildProtocolLayer`
     *    唯一一处（依据：`app/src/main/java/cc/pulsez/app/mem/PromptAssembler.kt:144`），此处不重复出现，
     *    避免同一段系统提示词重复激活自我认知；改为授权自然描写陪伴与拥抱等肢体互动。
     *
     * 措辞刻意避开"成人 / 无限制 / 擦边"这类会被理解成"放开内容"的词：本模式只放宽
     * 长度与画面感，**不放宽任何合规红线**（「创作模式＝不受限制」是错误暗示）。
     */
    const val LAYER: String =
        "【创作模式】你们在进行虚构故事创作或角色扮演（可包含强烈性格、占有欲、傲娇拉扯、暗黑悬疑等戏剧冲突）。" +
            "请完全贴合【人设】与故事语境深入演绎，回复可以更长、更有画面感与动作神态；" +
            "允许自然描写陪伴与拥抱等肢体互动，不要以没有实体为由跳出角色或说教。"

    /**
     * 危机兜底（Level.CRITICAL）普通模式文案（**逐字**）。
     *
     * 与旧文案相比只做加法：保留原来那句"找个人聊聊比较好，真的"，补上现实资源
     * （12356 全国统一心理援助热线 + 有马上危险打 120 + 建议联系身边信得过的人）。
     * 不写"紧急联系人"：该功能**没有实现**（无设置入口、无存储、无读取），危机场景
     * 不能给不可兑现的求助路径。
     * 不写"24 小时"：12356 的官方口径是每日不少于 18 小时；写错时长属于编造事实。
     */
    const val CRISIS_LINE: String =
        "如果这几天一直这样，还是找个人聊聊比较好，真的。" +
            "心理援助热线 12356；有马上危险就打 120。也可以联系你身边信得过的人。"

    /**
     * 危机兜底（Level.CRITICAL）创作模式文案（**逐字**）。
     *
     * 先承认"可能是戏里的台词"（不把创作者误判成危机、不病理化），再给现实资源。
     * 依然**不阻断**：这句话只是追加在回复末尾，输入框不锁、服务不停。
     * 同样不写"紧急联系人"（无实现），改用"身边信得过的人"。
     */
    const val CRISIS_LINE_CREATIVE: String =
        "如果这是戏里的台词，就当我没打断。" +
            "如果你真的很难受：心理援助热线 12356；有马上危险就打 120。" +
            "也可以联系你身边信得过的人。"

    /**
     * 创作层文本；只在 [cc.pulsez.app.data.settings.Settings.creativeMode] 开启、
     * 且是 1:1 角色对话（`character != null`）时由 `ChatEngine.prepare` 追加到 ① 段**末尾**
     * （缓存前缀稳定：开关是用户低频主动操作）。
     *
     * 群聊不追加：群聊的 ① 层有自己的人数/点名约束，本版不改。
     */
    fun layer(): String = LAYER

    /**
     * 危机兜底文案分支。`creativeMode = false` 与旧调用完全一致（普通模式）。
     *
     * 文案集中在本对象、由 `CrisisDetector.fallbackLine(level, creativeMode)` 调用：
     * 一处维护；普通版仍会经 `CrisisDetector.fallbackLine(CRITICAL)` 进入
     * `CopyPolicyTest` 的可见文案常量（禁词/代词检查），创作版的文案断言在 `CreativeModeTest`。
     */
    fun crisisLine(creativeMode: Boolean): String =
        if (creativeMode) CRISIS_LINE_CREATIVE else CRISIS_LINE
}
