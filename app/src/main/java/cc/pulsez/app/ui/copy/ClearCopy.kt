package cc.pulsez.app.ui.copy

/**
 * 「清空所有数据」的用户可见文案（v0.5.2 `）。
 *
 * 为什么收口成常量：确认框的「会删 / 会留」必须与 `ExportService.clearAll` 的实行为
 * **一一对应**，而 Compose 页面里的字面量没法在纯 JVM 里收集断言（同 `ReadCopy`/`UpdateCopy`
 * 的口径）；逐字断言与禁用词回归只能靠这个常量入口（`ClearCopyTest`）。
 *
 * 设计口径（` A）：
