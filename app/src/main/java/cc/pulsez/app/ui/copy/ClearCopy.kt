 *   键名清单；实现里 `wipeUserData()` 的 `clear()` 会清掉全部键（含识图能力探测这类内部
 *   派生数据），清单不重复列内部细节；
 * - 「会留」只有协议同意记录（版本 + 时间），避免用户重过 18 岁门槛；
 * - 失败文案：「没清干净」+ 一句可执行出路，不得声称已全清。
 *
 * 文案纪律：不出现 token / 上下文 / 窗口 / 向量 / embedding / 记忆检索 / 关键词 / 缓存 /
 * TTS / 语音合成；角色代词只用 TA；「密钥 / 地址」是用户必须自己填的技术词，按既有
 * `ReadCopyTest`/`WarmCopyTest` 口径允许。
 */
